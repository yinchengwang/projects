#ifndef DB_SPI_PUSHDOWN_H
#define DB_SPI_PUSHDOWN_H

#include "common/error.h"
#include "common/types.h"
#include "storage/value.h"

/*
 * 谓词下推（v0.9 定稿；W-D 之后加宽到「合取」）。
 *
 * 【为什么需要它】
 *
 * 向量检索的"过滤 + ANN"是同一件事的两面：
 * 前过滤（pre-filter）让索引失效 —— 索引只对"不加过滤"的查询友好；
 * 后过滤（post-filter）召回不足 —— 先取 top-k 再过滤，可能过滤完只剩几条。
 *
 * 真正管用的做法是**把过滤吸收进索引**（比如 DiskANN 的过滤感知遍历）。
 * 而"哪些过滤能吸收、怎么吸收"只有模态自己知道 ——
 * 所以它必须是一个接口，而不是优化器里的 if-else。
 *
 * 【下推的结果是一个行源】
 *
 * push() 返回的 AmScan 和 scan_begin() 返回的**完全同构**：
 * 都是"给我下一行的 (rid, 字节串)"。
 *
 * 于是执行器只有一种取行路径 —— 不需要为下推新增算子类型。
 * 这和 §5.2 的"能力协商靠返回值"是同一个思路：
 * **新机制不改变老机制的形状。**
 *
 * 【下推不改变正确性】
 *
 * 执行器拿到下推的行之后，**仍然完整求值一遍 WHERE**。
 * 下推只是"少读一些行"，不是"替你判断"。
 *
 * 于是下推实现错了，最多变慢，不会是错 —— 除非它漏行。
 * 所以下推的实现必须**保守**：宁可多给行，不能少给。
 *
 * 【谁决定能不能下推】
 *
 * can_push 由**模态**回答："这组谓词我能处理吗"。
 * 执行器不自己判断 —— 它不知道 blob 有没有索引、不知道图模态
 * 能不能按属性过滤。执行器只负责把表达式翻译成 Predicate。
 *
 * ==================== 为什么是一个数组，而不是一个谓词 ====================
 *
 * 第一版只能带**一个** Predicate。于是 `WHERE time >= a AND time < b` 变成
 * 「挑一个推，另一个交给执行器复检」—— 而执行器只能挑**一个**下推，
 * 所以双边界范围实际上只推一边：
 *
 *   time >= D2                    ⇒ 2 个分区
 *   time >= D2 AND time < D3      ⇒ **还是 2 个分区**（只推了 >= D2）
 *   真正想要的是 1 个分区
 *
 * 这不是某个模态的问题，是**契约太窄**：谓词的天然单位是"合取"，
 * 而接口强迫调用方把它拆成单个。所以这里改成数组 ——
 * **一次下推带一整组合取谓词**。
 *
 * ⚠️ `n == 1` 就是原来那个语义，所以这是**同一份契约的加宽**，
 *    不是"再加一个并存的 API"（两个并存会出现"哪个才是权威"的歧义）。
 *
 * ⚠️ 模态可以只用其中一部分（超集永远安全），但**不能漏行**。
 *    用不上就返回 E_NOTSUP，执行器会退回去挑最窄的单谓词。
 */

/* 谓词的比较算子。query 层必须翻译成这套编码（见 query/exec.c）。 */
#define PD_EQ   '='
#define PD_LT   '<'
#define PD_GT   '>'
#define PD_LE   'L'   /* <= */
#define PD_GE   'G'   /* >= */
#define PD_NE   'N'   /* <> */

/*
 * 一个谓词：列号 + 比较符 + 常量。
 *
 * 只支持"列 和 常量"这种形状 —— 这是能被下推的谓词的公共子集。
 * 更复杂的（列 vs 列、子查询、函数）留在执行器里求值。
 */
typedef struct {
    int     col_idx;       /* 列号（模态的列定义里的下标） */
    int     op;            /* PD_* */
    DbValue val;           /* 比较的常量 */
} Predicate;

/*
 * 一次下推最多带几条合取谓词。
 *
 * 4 够用：实际出现的形状几乎都是「一个等值 / 一个下界 / 一个上界 / 再来一个」。
 * 每条 Predicate 约 320 字节（DbValue 里带 256 字节文本缓冲），
 * 所以 4 条 ≈ 1.3 KB —— 执行器把它放在栈上，这个量级可接受。
 * 超过就只取前 4 条（**取子集永远安全**：合取的子集给的是超集），
 * 不截断成"看起来推了其实没推"的半截语义。
 */
#define PD_CONJ_MAX 4u

/* 前置声明（避免和 storage_am.h 互相 include） */
typedef struct StorageAM StorageAM;
typedef struct AmScan    AmScan;

/*
 * 模态说"这组合取谓词我能处理吗"。
 *
 * n 总是 >= 1。返回 OK 表示可以（随后调 push，参数**逐字相同**）；
 * E_NOTSUP 表示不行 —— 执行器会退回去逐条问 can_push(…, 1)，
 * 然后挑选择率最小的那一条单独下推。
 *
 * ⚠️ 判据要**严格**：只要组里有任何一条本模态处理不了，就整体 E_NOTSUP。
 *    迁就着"用能用的那几条"会让 EXPLAIN 显示的下推条件和实际不符，
 *    而下推是个看不见的优化 —— 说不清就等于没法维护。
 */
typedef int (*CanPushFn)(StorageAM *am, const Predicate *ps, u32 n);

/*
 * 把一组合取谓词交给模态，模态返回一个**行源**。
 * 行源和全表扫描同构：scan_next 给 (rid, 字节串)。
 *
 * ⚠️ 模态**允许**只用其中一部分（超集永远安全），但一旦它接受了
 *    这组合取（can_push 返回 OK），就**必须**保证给的是超集。
 */
typedef int (*PushFn)(StorageAM *am, const Predicate *ps, u32 n, AmScan **out);

#endif /* DB_SPI_PUSHDOWN_H */
