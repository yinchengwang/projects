#ifndef DB_WAL_WAL_HDR_H
#define DB_WAL_WAL_HDR_H

#include <stdio.h>

#include "common/types.h"

/*
 * wal_hdr.h —— WAL **文件头**的读写与校验（v1.3 欠账 6 / W-D 的 D-1）
 *
 * 【为什么单独一层】
 *
 * 两件事：
 *   1. 判据必须**只有一处**。文件头要在三个地方用到 ——
 *      wal_open 的「空文件分支」、wal_open 的「已有文件分支」、wal_reset 之后。
 *      判据散在三处 ⇒ 早晚有一处漏字段，而漏掉的那个字段恰好就是静默损坏的来源。
 *   2. `wal.c` 已经 760 行，加上这块会破 800 行硬规则 4
 *      （README.md:158「单文件不超过 800 行。超了就拆」）。
 *      按 MODALITIES.md 的坑 M6-68：到了上限要**拆**，不是「再挤一挤」。
 *
 * 【这一层解决什么问题】
 *
 * 原来 `wal_open` 直接 `fopen(path, "r+b")`，**不校验任何格式**。
 * 一份格式不兼容的 WAL（旧版本写的、或者根本不是 WAL）被打开后，
 * 恢复逻辑会按自己的格式去解析它 —— 最坏情况不是报错，而是**恢复出错误的数据**。
 *
 * 文件头把「不兼容」变成**开库时的一个显式错误**。
 *
 * 【为什么旧格式不提供兼容读 —— 这不是偷懒，是没有依据】
 *
 * 文件头之前的那套格式**没有任何版本标记**。所以一份「看起来像 v0」的文件，
 * 和一份「被改坏了的 v1」，在字节层面**无法区分**。
 * 「兼容 v0」只能靠猜，而猜错的代价是恢复出错误数据。
 * ⇒ 取「明确报 E_CORRUPT」：宁可让用户重建库，不可静默读错。
 *
 * 升级代价说白了：**加了文件头之后，旧库需要重建**（或另写迁移工具）。
 *
 * 【文件头的字段布局与取值见 wal.h 的 WalFileHeader / WAL_MAGIC 等宏】
 */

/*
 * 打开时把文件头准备好：空文件补写一个、非空文件校验一个。
 *
 * 返回：
 *   OK        —— *size_out 是**含文件头**的文件总字节数
 *   E_CORRUPT —— 文件比一个头还短（截断），或五个字段有任一不符
 *   E_IO      —— 读/写失败
 *
 * 三个内部分支**刻意不合并**（见 wal_hdr.c 的说明）：
 *   0 字节      ⇒ 全新库，写头
 *   1..31 字节  ⇒ 写到一半断电，半个头 ⇒ E_CORRUPT
 *   >= 32 字节  ⇒ 逐字段校验
 */
int wal_hdr_load(FILE *f, u64 *size_out);

/*
 * 在文件**最前面**写一个合法的文件头。
 * 调用方保证此刻文件是空的（wal_reset 用 "wb" 重开之后、或全新文件）。
 */
int wal_hdr_write(FILE *f);

/*
 * 校验一段已经读出来的头（32 字节）。
 * 每个字段都查 —— 见 wal.c 里「为什么 page_size 与 endian_marker 也要校验」。
 */
int wal_hdr_check(const u8 *h);

#endif /* DB_WAL_WAL_HDR_H */
