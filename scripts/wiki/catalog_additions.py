def apply_additions(existing, additions):
    """把新增条目并入既有清单；已存在的 name 以 existing 为准。

    返回新列表，不修改入参；结果按 tier / model / name 排序，
    保证下游 manifest 生成顺序稳定。
    """
    seen = {entry["name"] for entry in existing}
    merged = list(existing)
    for entry in additions:
        if entry["name"] in seen:
            continue
        seen.add(entry["name"])
        merged.append(entry)
    return sorted(merged,
                  key=lambda e: (e["tier"], e["model"], e["name"]))
